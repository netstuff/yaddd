"""Render generated rules, AGENTS.md and machine configuration."""

from __future__ import annotations

import json
from pathlib import Path

from yaddd_agents.lock import build_lock
from yaddd_agents.model import (
    LAYERS,
    MANAGED_BEGIN,
    MANAGED_END,
    AgentsError,
    Project,
    Resolution,
)
from yaddd_agents.resolve import layers_config

AGENTS_PATH = Path("AGENTS.md")
LAYERS_PATH = Path(".yaddd/layers.json")
LOCK_PATH = Path(".agents/manifest.lock.json")
BASE_RULES = Path(".agents/rules/base")
EXTENSION_RULES = Path(".agents/rules/extensions")
LOCAL_RULES = Path(".agents/rules/local")


class RenderError(AgentsError):
    """Generated content cannot be rendered safely."""


def expected_outputs(project: Project, resolution: Resolution) -> dict[Path, str]:
    """Return every generated file and its exact content."""
    outputs: dict[Path, str] = {}
    base = resolution.packs[0]
    for doc_path, content in base.docs.items():
        if doc_path == base.core_doc:
            continue
        outputs[BASE_RULES / Path(doc_path).name] = content

    for pack in resolution.packs[1:]:
        for doc_path, content in pack.docs.items():
            outputs[EXTENSION_RULES / pack.name / Path(doc_path).name] = content

    outputs[AGENTS_PATH] = render_agents_md(project, resolution, outputs)
    outputs[LAYERS_PATH] = json.dumps(layers_config(resolution), indent=2, sort_keys=True) + "\n"
    outputs[LOCK_PATH] = build_lock(project, resolution, outputs)
    return outputs


def render_agents_md(project: Project, resolution: Resolution, outputs: dict[Path, str]) -> str:
    """Build AGENTS.md, preserving everything outside the managed block."""
    base = resolution.packs[0]
    core = base.docs.get(base.core_doc, "").strip() if base.core_doc else ""
    routing = _render_routing(project, outputs)
    block = "\n\n".join(
        part
        for part in (
            MANAGED_BEGIN,
            core,
            routing,
            _generated_note(),
            MANAGED_END,
        )
        if part
    )
    path = project.root / AGENTS_PATH
    existing = path.read_text(encoding="utf-8") if path.is_file() else _default_header()
    return replace_managed_block(existing, block)


def _default_header() -> str:
    """Return the header used when AGENTS.md does not exist yet."""
    return "# Rules for AI agents and humans working in this repository.\n"


def replace_managed_block(text: str, block: str) -> str:
    """Replace or append the yaddd-agents managed block."""
    starts = text.count(MANAGED_BEGIN)
    ends = text.count(MANAGED_END)
    if starts == 0 and ends == 0:
        prefix = text.rstrip()
        return f"{prefix}\n\n{block}\n" if prefix else f"{block}\n"
    if starts != 1 or ends != 1:
        raise RenderError("AGENTS.md must contain exactly one yaddd-agents managed block")
    start = text.index(MANAGED_BEGIN)
    end = text.index(MANAGED_END) + len(MANAGED_END)
    return f"{text[:start]}{block}{text[end:]}"


def _render_routing(project: Project, outputs: dict[Path, str]) -> str:
    """Render the layer-to-file routing section."""
    lines = [
        "## How to apply these rules",
        "",
        "The rules in this managed block are **core** and always apply. Before editing",
        "files under a layer, read that layer's files. They are **additive**: they add",
        "constraints and never relax core rules. On conflict, core wins.",
        "",
    ]
    for layer in LAYERS:
        files = _layer_files(project, outputs, layer)
        if files:
            rendered = ", ".join(f"`{path}`" for path in files)
            lines.append(f"- **{layer}**: {rendered}")

    local_core = project.local_rules_dir / "core.md"
    if local_core.is_file():
        lines.extend(
            [
                "",
                "## Project-specific rules",
                "",
                f"- `{LOCAL_RULES / 'core.md'}`",
            ]
        )
    return "\n".join(lines)


def _layer_files(project: Project, outputs: dict[Path, str], layer: str) -> list[str]:
    """Return generated and local rule files for one layer."""
    files: list[str] = []
    base = BASE_RULES / f"{layer}.md"
    if base in outputs:
        files.append(base.as_posix())
    for path in sorted(outputs):
        if path.parent.parent == EXTENSION_RULES and path.name == f"{layer}.md":
            files.append(path.as_posix())
    local = LOCAL_RULES / f"{layer}.md"
    if (project.root / local).is_file():
        files.append(local.as_posix())
    return files


def _generated_note() -> str:
    """Return the note explaining which files are generated."""
    return "\n".join(
        [
            "## Generated files",
            "",
            f"`{BASE_RULES.as_posix()}/` and `{EXTENSION_RULES.as_posix()}/` are generated by",
            "`yaddd-agents sync`. Do not edit them. Put project-specific rules in",
            f"`{LOCAL_RULES.as_posix()}/` and run `yaddd-agents sync`.",
        ]
    )


def write_outputs(project: Project, outputs: dict[Path, str]) -> None:
    """Write expected files and remove stale generated files."""
    for relative, content in outputs.items():
        path = project.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")

    project.local_rules_dir.mkdir(parents=True, exist_ok=True)
    _remove_stale(project, outputs)


def _remove_stale(project: Project, outputs: dict[Path, str]) -> None:
    """Remove generated files that are no longer expected."""
    for root in (BASE_RULES, EXTENSION_RULES):
        directory = project.root / root
        if not directory.is_dir():
            continue
        for path in sorted(directory.rglob("*"), reverse=True):
            if path.is_dir():
                try:
                    path.rmdir()
                except OSError:
                    pass
                continue
            relative = path.relative_to(project.root)
            if relative not in outputs:
                path.unlink()


def check_outputs(project: Project, outputs: dict[Path, str]) -> list[str]:
    """Return a list of missing, stale or unexpected generated files."""
    problems: list[str] = []
    for relative, expected in outputs.items():
        path = project.root / relative
        if not path.is_file():
            problems.append(f"missing: {relative.as_posix()}")
            continue
        if path.read_text(encoding="utf-8") != expected:
            problems.append(f"stale: {relative.as_posix()}")

    for root in (BASE_RULES, EXTENSION_RULES):
        directory = project.root / root
        if not directory.is_dir():
            continue
        for path in directory.rglob("*"):
            if path.is_file():
                relative = path.relative_to(project.root)
                if relative not in outputs:
                    problems.append(f"unexpected: {relative.as_posix()}")
    return sorted(problems)
